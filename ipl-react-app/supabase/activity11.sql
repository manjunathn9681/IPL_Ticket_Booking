CREATE OR REPLACE FUNCTION public.book_ticket(
  p_match_id integer,
  p_customer_name text,
  p_tickets integer,
  p_stand text
)
RETURNS public.bookings
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_match public.matches%ROWTYPE;
  v_ticket_price integer;
  v_booking public.bookings%ROWTYPE;
BEGIN
  IF p_customer_name IS NULL
    OR char_length(btrim(p_customer_name)) NOT BETWEEN 1 AND 120 THEN
    RAISE EXCEPTION 'Enter a customer name (up to 120 characters).';
  END IF;

  IF p_tickets IS NULL OR p_tickets < 1 THEN
    RAISE EXCEPTION 'Choose at least one ticket.';
  END IF;

  IF p_stand IS NULL OR p_stand NOT IN ('General', 'Premium', 'VIP') THEN
    RAISE EXCEPTION 'Choose a valid ticket category.';
  END IF;

  SELECT m.* INTO v_match
  FROM public.matches AS m
  WHERE m.id = p_match_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Match not found.';
  END IF;

  v_ticket_price := CASE p_stand
    WHEN 'General' THEN v_match.general_price
    WHEN 'Premium' THEN v_match.premium_price
    WHEN 'VIP' THEN v_match.vip_price
  END;

  UPDATE public.matches
  SET available_seats = available_seats - p_tickets
  WHERE id = p_match_id
    AND available_seats >= p_tickets;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Not enough seats available.';
  END IF;

  INSERT INTO public.bookings
    (match_id, customer_name, tickets, stand, ticket_price, total_price)
  VALUES
    (p_match_id, btrim(p_customer_name), p_tickets, p_stand, v_ticket_price, v_ticket_price * p_tickets)
  RETURNING * INTO v_booking;

  RETURN v_booking;
END
$$;

REVOKE ALL ON FUNCTION public.book_ticket(integer, text, integer, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.book_ticket(integer, text, integer, text) TO anon, authenticated;


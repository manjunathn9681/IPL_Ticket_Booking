CREATE TABLE IF NOT EXISTS public.matches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teams text NOT NULL,
  match_date timestamptz NOT NULL,
  venue text NOT NULL,
  general_price integer NOT NULL CHECK (general_price > 0),
  premium_price integer NOT NULL CHECK (premium_price > 0),
  vip_price integer NOT NULL CHECK (vip_price > 0),
  available_seats integer NOT NULL CHECK (available_seats >= 0)
);

CREATE TABLE IF NOT EXISTS public.bookings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id integer NOT NULL REFERENCES public.matches(id) ON DELETE RESTRICT,
  customer_name text NOT NULL CHECK (char_length(btrim(customer_name)) BETWEEN 1 AND 120),
  tickets integer NOT NULL CHECK (tickets > 0),
  stand text NOT NULL CHECK (stand IN ('General', 'Premium', 'VIP')),
  ticket_price integer NOT NULL CHECK (ticket_price > 0),
  total_price integer NOT NULL CHECK (total_price > 0),
  booking_date timestamptz NOT NULL DEFAULT now(),
  CHECK (total_price = tickets * ticket_price)
);

